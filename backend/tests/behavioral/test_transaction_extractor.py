"""
Acceptance tests for services/transaction_extractor.py against FICTIONAL synthetic statements
(tests/fixtures, generated by testing/make_synthetic_statement.py). Extraction accuracy is tested
separately from classification accuracy. The extractor is standalone and must stay unwired.
"""
import json
import pathlib
from decimal import Decimal

import pytest

from services.deposit_classifier import DepositCategory, ReviewStatus
from services.transaction_extractor import extract_and_classify, extract_transactions, to_transactions

FIX = pathlib.Path(__file__).resolve().parent.parent / "fixtures"
D = Decimal


def load(name):
    pdf = (FIX / f"synthetic_statement_{name}.pdf").read_bytes()
    truth = json.loads((FIX / f"synthetic_statement_{name}.truth.json").read_text())
    return pdf, truth


@pytest.fixture(scope="module")
def good():
    pdf, truth = load("hard_cases")
    return extract_and_classify(pdf), truth


# ---------------------------------------------------------------- extraction accuracy

def test_every_synthetic_transaction_is_extracted(good):
    outcome, truth = good
    assert len(outcome.result.rows) == len(truth["rows"]) == 25
    assert outcome.result.failures == []


def test_dates_amounts_direction_and_balances_are_exact(good):
    outcome, truth = good
    for row, t in zip(outcome.result.rows, truth["rows"]):
        assert row.date.isoformat() == t["date"]
        assert row.debit == (D(t["debit"]) if t["debit"] else None)
        assert row.credit == (D(t["credit"]) if t["credit"] else None)
        assert (row.debit is None) != (row.credit is None)  # exactly one direction
        assert row.balance == D(t["balance"])


def test_original_descriptions_are_preserved_including_wrapped_lines(good):
    outcome, truth = good
    assert [r.description for r in outcome.result.rows] == [t["description"] for t in truth["rows"]]
    long = [r for r in outcome.result.rows if "KHUMALO" in r.description][0]
    assert long.description.endswith("INVOICE 20481 FEBRUARY ORDER")


def test_identical_rows_on_the_same_day_are_both_kept(good):
    outcome, _ = good
    yoco = [r for r in outcome.result.rows if r.description == "YOCO CARD SETTLEMENT"]
    assert len(yoco) == 2 and yoco[0].date == yoco[1].date and yoco[0].credit == yoco[1].credit


def test_repeated_monthly_payments_and_month_end_rows_are_kept(good):
    outcome, _ = good
    abc = [r for r in outcome.result.rows if r.description == "PAYMENT FROM ABC TRADERS"]
    assert len(abc) == 4
    dates = {(r.date.month, r.date.day) for r in outcome.result.rows}
    assert {(1, 31), (2, 28), (3, 1), (3, 31)} <= dates


def test_period_is_read_from_the_statement(good):
    r = good[0].result
    assert (r.period_start.isoformat(), r.period_end.isoformat()) == ("2026-01-01", "2026-03-31")


# ---------------------------------------------------------------- reconciliation

def test_statement_reconciles_and_is_trustworthy(good):
    rec = good[0].result.reconciliation
    assert rec.opening_balance + rec.total_credits - rec.total_debits == rec.closing_balance
    assert rec.statement_reconciles and rec.difference == 0 and rec.row_balance_mismatches == []
    assert good[0].result.trustworthy


def test_a_missing_row_is_detected_by_reconciliation():
    pdf, _ = load("missing_row")
    result = extract_transactions(pdf)
    assert len(result.rows) == 24
    assert not result.reconciliation.statement_reconciles
    assert result.reconciliation.difference == D("7500.00")  # the dropped SALE OF EQUIPMENT credit
    assert result.reconciliation.row_balance_mismatches
    assert not result.trustworthy


def test_a_misread_amount_is_reported_not_dropped_silently():
    pdf, truth = load("garbled_amount")
    result = extract_transactions(pdf)
    assert len(result.failures) == 1 and "4,5O0.00" in result.failures[0].reason
    assert len(result.rows) + len(result.failures) == len(truth["rows"])  # every row accounted for
    assert not result.trustworthy


def test_untrustworthy_statements_produce_no_revenue_observation():
    for name in ("missing_row", "garbled_amount"):
        outcome = extract_and_classify(load(name)[0])
        assert outcome.observation is None and outcome.blocked_reason


@pytest.mark.parametrize("blob", [b"", b"not a pdf", b"%PDF-1.4 truncated"])
def test_unreadable_input_fails_loudly_without_raising(blob):
    result = extract_transactions(blob)
    assert result.failures and not result.trustworthy


# ---------------------------------------------------------------- hand-off to classifier / normaliser

def test_only_deposits_are_passed_to_the_classifier(good):
    outcome, truth = good
    assert len(outcome.classified) == sum(1 for t in truth["rows"] if t["credit"]) == 19
    assert all(c.transaction.amount > 0 for c in outcome.classified)
    assert any(t.amount < 0 for t in to_transactions(outcome.result))  # debits exist, just not classified


def by_desc(outcome, desc):
    return [c for c in outcome.classified if c.transaction.description == desc]


@pytest.mark.parametrize("desc,category", [
    ("OWNER CAPITAL INJECTION", DepositCategory.OWNER_CONTRIBUTION),
    ("BUSINESS LOAN DISBURSEMENT", DepositCategory.LOAN),
    ("TRANSFER FROM SAVINGS", DepositCategory.INTERNAL_TRANSFER),
])
def test_clear_non_revenue_deposits_are_excluded(good, desc, category):
    (c,) = by_desc(good[0], desc)
    assert c.category is category and not c.counts_as_revenue


@pytest.mark.parametrize("desc", ["LOAN REPAYMENT INVOICE", "CUSTOMER REFUND", "CASH DEPOSIT 88213"])
def test_ambiguous_and_unknown_deposits_go_to_review_and_are_not_revenue(good, desc):
    (c,) = by_desc(good[0], desc)
    assert c.review_status is ReviewStatus.NEEDS_REVIEW and not c.counts_as_revenue


def test_normalisation_uses_only_eligible_classified_customer_revenue(good):
    outcome, truth = good
    ob = outcome.observation
    eligible = sum(c.transaction.amount for c in outcome.classified if c.counts_as_revenue)
    assert ob.observed_customer_revenue == eligible
    assert ob.total_deposits == sum(D(t["credit"]) for t in truth["rows"] if t["credit"])
    parts = ob.observed_customer_revenue + ob.unresolved_deposits + sum(ob.excluded_by_category.values())
    assert parts == ob.total_deposits  # every deposit is in exactly one bucket
    assert ob.unresolved_deposits == D("12650.00") and ob.needs_review_count == 5
    assert ob.basis == "run_rate" and ob.months_covered == 3.0


# ---------------------------------------------------------------- classifier quality on the synthetic set (measured separately)

def truth_for(outcome, truth, c):
    t = c.transaction
    (row,) = [r for r in truth["rows"] if r["description"] == t.description and r["credit"]
              and D(r["credit"]) == t.amount and r["date"] == t.date.isoformat()][:1]
    return row["true_category"]


def test_classifier_baseline_on_synthetic_deposits(good):
    """Pinned baseline (rules-v2): 11 genuine sales; 10 found, 1 sent to review, 0 false positives."""
    outcome, truth = good
    tp = fp = fn = 0
    for c in outcome.classified:
        actual = truth_for(outcome, truth, c) == "sale"
        tp += actual and c.counts_as_revenue
        fp += (not actual) and c.counts_as_revenue
        fn += actual and not c.counts_as_revenue
    assert (tp, fp, fn) == (10, 0, 1)
    true_revenue = sum(D(r["credit"]) for r in truth["rows"] if r["true_category"] == "sale")
    assert true_revenue == D("41350.00")
    # conservative: understated by the R2,200 'OWNER STORES PAYMENT' held for review, never overstated
    assert outcome.observation.observed_customer_revenue == D("39150.00")
    assert outcome.observation.observed_customer_revenue <= true_revenue


def test_asset_sale_is_not_counted_as_customer_revenue(good):
    (c,) = by_desc(good[0], "SALE OF EQUIPMENT")
    assert not c.counts_as_revenue


def test_customer_whose_name_contains_a_keyword_is_not_excluded(good):
    (c,) = by_desc(good[0], "OWNER STORES PAYMENT")
    assert c.counts_as_revenue or c.review_status is ReviewStatus.NEEDS_REVIEW


# ---------------------------------------------------------------- isolation

def test_extractor_is_not_wired_into_production_code():
    root = pathlib.Path(__file__).resolve().parents[2]
    offenders = []
    for path in root.rglob("*.py"):
        rel = path.relative_to(root).as_posix()
        if rel.startswith(("tests/", "testing/", "venv", ".venv")) or rel.endswith("transaction_extractor.py"):
            continue
        if "transaction_extractor" in path.read_text(encoding="utf-8-sig", errors="ignore"):
            offenders.append(rel)
    assert offenders == []
